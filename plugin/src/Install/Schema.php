	public const OPTION     = 'rungud_db_version';

	/** @return list<string> table names without prefix */
	public static function tables(): array {
		return array_keys( self::definitions() );
	}

	public static function table( string $name ): string {
		global $wpdb;
		return $wpdb->prefix . 'rungud_' . $name;
	}

	public static function install(): void {
		global $wpdb;
		require_once ABSPATH . 'wp-admin/includes/upgrade.php';
		$charset = $wpdb->get_charset_collate();
		foreach ( self::definitions() as $name => $columns ) {
			dbDelta( 'CREATE TABLE ' . self::table( $name ) . " (\n{$columns}\n) {$charset};" );
		}
		Seed::run();
		update_option( self::OPTION, self::DB_VERSION, false );
	}

