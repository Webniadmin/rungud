/**
 * The plugin's own tables — only what the site does not have (PROMPT.md §2).
 * Everything else (users, orders, products, memberships, licences, coupons) is
 * read live and never copied here.
 *
 * Conventions: money DECIMAL(12,2) + CHAR(3) currency; JSON in LONGTEXT;
